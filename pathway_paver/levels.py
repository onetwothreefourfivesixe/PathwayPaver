def _validate_levels():
    """Fail fast if a layout doesn't match the grid size."""
    for level in levels:
        layout = level["layout"]
        if len(layout) != num_rows_level:
            raise ValueError(f"{level['name']}: expected {num_rows_level} rows, got {len(layout)}")
        for i, row in enumerate(layout):
            if len(row) != num_cols_level:
                raise ValueError(f"{level['name']} row {i}: expected {num_cols_level} columns, got {len(row)}")


_validate_levels()
